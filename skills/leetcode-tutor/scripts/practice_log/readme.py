"""The Practice Workspace's README.md: a fixed header, then the index of Problems.

`init` writes it for an empty workspace and `index` regenerates it from the Practice Log, so both
produce the same text. Everything here is a pure function of the Problems it is given.
"""

HEADER = """\
# Practice Log

My coding-interview practice, recorded by [LeetCode Tutor](https://github.com/mileschintw/leetcode-tutor).

- `problems/<source>/<slug>/`: one folder per Problem, with `notes.md` (the Problem, its Key Takeaway and every Attempt) and the code from each Attempt.
- `review-sheets/`: Review Sheets saved before interviews.
- `practice-log.json`: workspace settings.

The Practice Log is this repository: edit it here, and treat any copy elsewhere as read-only.

<!-- Generated by `practice-log index` from each Problem's notes.md. Edit the notes, not this file. -->
"""

README_FILE = "README.md"
NO_LIST = "No list"
UNTAGGED = "Untagged"
NONE = "—"


class Problem:
    """What the index shows of one Problem. Attempt count and last date come from its Attempts."""

    def __init__(self, folder, problem_id, title, difficulty, tags, lists, need_review, reason, dates):
        self.folder = folder  # POSIX path relative to the workspace root
        self.id = problem_id
        self.title = title
        self.difficulty = difficulty
        self.tags = tags
        self.lists = lists
        self.need_review = need_review
        self.reason = reason
        self.attempts = len(dates)
        self.last_date = max((date for date in dates if date), default="")


def render(problems):
    problems = sorted(problems, key=lambda p: (p.title.casefold(), p.id, p.folder))
    if not problems:
        return HEADER + "\nNo Problems yet.\n"

    review = [p for p in problems if p.need_review]
    attempts = sum(p.attempts for p in problems)
    parts = [
        HEADER,
        f"{plural(len(problems), 'Problem')}, {plural(attempts, 'Attempt')}, {len(review)} to review.\n",
        "## Need Review\n",
    ]
    if review:
        parts.append(table(("Problem", "Difficulty", "Reason", "Attempts", "Last Attempt"), review, review_row))
    else:
        parts.append("Nothing to review.\n")

    parts.append("## By Problem List\n")
    parts += groups(problems, lambda p: p.lists, NO_LIST)
    parts.append("## By Topic\n")
    parts += groups(problems, lambda p: p.tags, UNTAGGED)
    return "\n".join(parts)


def groups(problems, names_of, fallback):
    """One `###` section per name, alphabetical, then one for the Problems with no name."""
    names = sorted({name for p in problems for name in names_of(p)}, key=lambda name: (name.casefold(), name))
    sections = [(name, [p for p in problems if name in names_of(p)]) for name in names]
    ungrouped = [p for p in problems if not names_of(p)]
    if ungrouped:
        sections.append((fallback, ungrouped))
    parts = []
    for name, members in sections:
        parts.append(f"### {name}\n")
        parts.append(table(("Problem", "Difficulty", "Need Review", "Attempts", "Last Attempt"), members, group_row))
    return parts


def table(headings, problems, row):
    lines = [cells(headings), cells("---" for _ in headings)]
    lines += [cells(row(p)) for p in problems]
    return "\n".join(lines) + "\n"


def review_row(p):
    return (link(p), difficulty(p), escape(p.reason), str(p.attempts), p.last_date or NONE)


def group_row(p):
    return (link(p), difficulty(p), "yes" if p.need_review else "", str(p.attempts), p.last_date or NONE)


def cells(values):
    return "| " + " | ".join(values) + " |"


def link(p, base=""):
    """A link to the Problem's notes.md; `base` leads from the linking file's folder to the workspace root."""
    text = escape(p.title).replace("[", "\\[").replace("]", "\\]")
    # Obsidian cannot link to a folder (it creates an empty note), so link the file; github.com renders it.
    return f"[{text}]({base}{p.folder}/notes.md)"


def difficulty(p):
    return p.difficulty.capitalize() if p.difficulty else ""


def escape(text):
    # Backslashes first, so a trailing `\` cannot escape the `|` or `]` that follows it.
    return text.replace("\\", "\\\\").replace("|", "\\|")


def plural(count, noun):
    return f"{count} {noun}{'' if count == 1 else 's'}"
