"""The artefacts `build` generates from the skills and the Claude Code plugin manifest.

Everything here is a pure function from source files to `{relative path: bytes}`, so `build` can
either write the result or compare it with what is committed. Paths are relative to the repo root.
"""

import json
import re
import zipfile
from io import BytesIO
from pathlib import PurePosixPath

from practice_log.frontmatter import FrontmatterError, read_text

# How a maintainer runs build; it appears in the generated prompt's header and in build's messages.
BUILD_COMMAND = "python skills/leetcode-tutor/scripts/practice_log build"
PROMPTS_DIR = "prompts"
DIST_DIR = "dist"
CLAUDE_PLUGIN = ".claude-plugin/plugin.json"

# Generated from CLAUDE_PLUGIN. Root plugin.json is the Agent Plugins manifest Codex and Cursor read;
# Antigravity reads the same file with a schema that forbids extra keys, hence only three keys.
AGENT_PLUGIN = "plugin.json"
AGENT_PLUGIN_SCHEMA = "https://agent-plugins.org/schemas/1.0.0/plugin.schema.json"
CURSOR_PLUGIN = ".cursor-plugin/plugin.json"
CODEX_MARKETPLACE = ".agents/plugins/marketplace.json"
CURSOR_KEYS = ("name", "description", "author", "homepage", "repository", "license", "keywords")

# Never shipped: Python caches appear once the skill's own scripts have run.
EXCLUDED_DIRS = ("__pycache__",)
EXCLUDED_SUFFIXES = (".pyc",)
EXCLUDED_NAMES = (".DS_Store",)
# Fixed so the same skill always zips to the same bytes.
ZIP_DATE = (1980, 1, 1, 0, 0, 0)
ZIP_FILE_MODE = 0o644 << 16

MARKDOWN_LINK = re.compile(r"\[([^\]\n]+)\]\(([^)\s]+)\)")
HEADING = re.compile(r"^# (.+)$", re.MULTILINE)
MARKER_START = "<!-- in the copy-paste prompt"
MARKER = re.compile(r"<!-- in the copy-paste prompt:(.*)-->")
PROMPT_HEADER = f"<!-- Generated by `{BUILD_COMMAND}` from skills/{{name}}/. Edit the skill, not this file. -->\n\n"


def skill_files(skill_dir):
    """Every file the skill ships, as (path relative to the skill folder, absolute path), sorted."""
    files = []
    for path in skill_dir.rglob("*"):
        rel = PurePosixPath(path.relative_to(skill_dir).as_posix())
        if not path.is_file() or any(part in EXCLUDED_DIRS for part in rel.parts):
            continue
        if rel.suffix in EXCLUDED_SUFFIXES or rel.name in EXCLUDED_NAMES:
            continue
        files.append((rel.as_posix(), path))
    return sorted(files)


def committed_artefacts(root, skill_dirs):
    """Generated files that are committed: copy-paste prompts and the other tools' plugin manifests."""
    artefacts = {f"{PROMPTS_DIR}/{d.name}.md": render_prompt(d).encode("utf-8") for d in skill_dirs}
    plugin = read_claude_plugin(root)
    if plugin is not None:
        artefacts.update(plugin_manifests(plugin))
    return artefacts


def dist_artefacts(skill_dirs, dependents=None):
    """Gitignored release files: one upload zip per platform layout, per skill.

    `dependents` maps a skill's name to the skills that need it installed alongside. They sit next to
    it in the `.agents/skills/` layout, so that zip carries them too; the other zips stay single-skill.
    """
    dependents = dependents or {}
    artefacts = {}
    for skill_dir in skill_dirs:
        name, files = skill_dir.name, skill_files(skill_dir)
        # claude.ai wants the skill folder at the zip root, named after the skill.
        artefacts[f"{DIST_DIR}/{name}-claude-ai.zip"] = make_zip(files, f"{name}/")
        # The Gemini app and Perplexity want SKILL.md itself at the zip root.
        artefacts[f"{DIST_DIR}/{name}-gemini-perplexity.zip"] = make_zip(files, "")
        # The cross-tool layout: unzip into a project or the home directory.
        members = [(f".agents/skills/{name}/{rel}", path) for rel, path in files]
        for dependent in sorted(dependents.get(name, []), key=lambda d: d.name):
            members += [(f".agents/skills/{dependent.name}/{rel}", path) for rel, path in skill_files(dependent)]
        artefacts[f"{DIST_DIR}/{name}-agents-skills.zip"] = make_zip(members, "")
    return artefacts


def make_zip(files, prefix):
    buffer = BytesIO()
    with zipfile.ZipFile(buffer, "w", zipfile.ZIP_DEFLATED) as archive:
        for rel, path in files:
            info = zipfile.ZipInfo(prefix + rel, date_time=ZIP_DATE)
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = ZIP_FILE_MODE
            archive.writestr(info, path.read_bytes())
    return buffer.getvalue()


def render_prompt(skill_dir):
    """SKILL.md's body followed by each reference file, with links to them turned into section names.

    Call it only on a skill `prompt_problems` passes.
    """
    sources = prompt_sources(skill_dir)
    texts = {rel: apply_markers(read_text(path))[0] for rel, path in sources}
    texts["SKILL.md"] = markdown_body(texts["SKILL.md"])
    titles = {rel: section_title(rel, text) for rel, text in texts.items() if rel != "SKILL.md"}

    parts = [rewrite_links(text, PurePosixPath(rel).parent, titles) for rel, text in texts.items()]
    body = "\n\n---\n\n".join(part.strip("\n") for part in parts)
    return PROMPT_HEADER.format(name=skill_dir.name) + body + "\n"


def prompt_sources(skill_dir):
    """SKILL.md, then each reference file, as (path relative to the skill folder, absolute path)."""
    references = [(rel, path) for rel, path in skill_files(skill_dir) if is_reference(rel)]
    return [("SKILL.md", skill_dir / "SKILL.md")] + references


def prompt_problems(skill_dir):
    """Why the skill's prompt can't be generated: an unreadable file or a malformed prompt marker."""
    problems = []
    for rel, path in prompt_sources(skill_dir):
        try:
            text = read_text(path)
        except FrontmatterError as error:
            problems.append(f"{rel}: {error}")
            continue
        problems += [f"{rel}: {problem}" for problem in apply_markers(text)[1]]
    return problems


def apply_markers(text):
    """(the text as the prompt shows it, problems with its markers).

    A `<!-- in the copy-paste prompt: <text> -->` line replaces the paragraph right after it with
    <text>, or drops it when <text> is empty: a pasted prompt has no skill folder, so a sentence about
    the skill's own files needs other words there. The marker line itself never reaches the prompt.
    """
    lines = text.splitlines(keepends=True)
    out, problems, i = [], [], 0
    while i < len(lines):
        line, number = lines[i], i + 1
        if not line.lstrip().startswith(MARKER_START):
            out.append(line)
            i += 1
            continue
        marker = MARKER.fullmatch(line.strip())
        i += 1
        if not marker:
            problems.append(f"line {number}: write the prompt marker as '{MARKER_START}: <replacement> -->' on one line")
            continue
        if i == len(lines) or not lines[i].strip():
            problems.append(f"line {number}: no paragraph right after the prompt marker for it to replace")
            continue
        while i < len(lines) and lines[i].strip():
            i += 1
        replacement = marker.group(1).strip()
        if replacement:
            out.append(replacement + "\n")
        elif i < len(lines):
            i += 1  # the blank line after a dropped paragraph
    return "".join(out), problems


def is_reference(rel):
    path = PurePosixPath(rel)
    return path.parts[0] == "references" and path.suffix == ".md"


def markdown_body(text):
    lines = text.splitlines(keepends=True)
    end = next(i for i in range(1, len(lines)) if lines[i].strip() == "---")
    return "".join(lines[end + 1 :])


def section_title(rel, text):
    match = HEADING.search(text)
    return match.group(1).strip() if match else rel


def rewrite_links(text, base, titles):
    """Point links to inlined reference files at their sections: the prompt has no files to open."""

    def replace(match):
        target = match.group(2).split("#", 1)[0]
        if not target or ":" in target:
            return match.group(0)
        rel = normalise(base / target)
        if rel not in titles:
            return match.group(0)
        return f'the "{titles[rel]}" section'

    return MARKDOWN_LINK.sub(replace, text)


def normalise(path):
    parts = []
    for part in path.parts:
        if part == "..":
            if parts:
                parts.pop()
        elif part != ".":
            parts.append(part)
    return "/".join(parts)


def read_claude_plugin(root):
    path = root / CLAUDE_PLUGIN
    if not path.exists():
        return None
    return json.loads(path.read_text(encoding="utf-8-sig"))


def plugin_manifests(plugin):
    """The Codex, Cursor and Antigravity manifests, derived from the Claude Code plugin manifest.

    The Codex marketplace points at the git repository, so it is generated only when the manifest
    names a `repository`.
    """
    name = plugin["name"]
    manifests = {
        AGENT_PLUGIN: {"$schema": AGENT_PLUGIN_SCHEMA, "name": name, "description": plugin["description"]},
        CURSOR_PLUGIN: cursor_manifest(plugin),
    }
    if "repository" in plugin:
        manifests[CODEX_MARKETPLACE] = {
            "name": name,
            "plugins": [
                {
                    "name": name,
                    # Codex's docs say to use a "url" source for a plugin at the repository root, but
                    # list no fields for it; "url" is assumed from their git-subdir example.
                    "source": {"source": "url", "url": git_url(plugin["repository"])},
                    "policy": {"installation": "AVAILABLE", "authentication": "ON_INSTALL"},
                    "category": "Productivity",
                }
            ],
        }
    return {path: to_json(manifest) for path, manifest in manifests.items()}


def cursor_manifest(plugin):
    cursor = {key: plugin[key] for key in CURSOR_KEYS if key in plugin}
    author = cursor.get("author")
    # Claude Code's author is an object; a plain string is taken as the name.
    if isinstance(author, str):
        cursor["author"] = {"name": author}
    elif author is not None:
        # Cursor's author takes only name and email.
        cursor["author"] = {k: v for k, v in author.items() if k in ("name", "email")}
    return cursor


def git_url(repository):
    return repository if repository.endswith(".git") else repository.rstrip("/") + ".git"


def to_json(value):
    return (json.dumps(value, indent=2, ensure_ascii=False) + "\n").encode("utf-8")
