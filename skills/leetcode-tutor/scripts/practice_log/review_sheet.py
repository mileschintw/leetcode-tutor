"""`review-sheet`: select Problems from the Practice Log by filters and write a Review Sheet.

Filters of one kind match any of their values; filters of different kinds must all match, so
`--list "Grind 75" --tag graph --tag tree` selects the Grind 75 Problems tagged graph or tree. Every
filter matches regardless of case. With no filters, every Problem is selected. A Problem is marked
to redo when it is Need Review, or when an Attempt's outcome is `saw-solution` and no later
full-Session Attempt was solved alone: imported records carry `saw-solution` without setting Need Review.
"""

import sys

from practice_log import readme
from practice_log.index import to_problem
from practice_log.notes import read_key_takeaway_line
from practice_log.problems import read_problems
from practice_log.validate import is_date
from practice_log.workspace import CONFIG_FILE

GENERATED = "<!-- Generated by `practice-log review-sheet` from the Practice Log. -->"
SHEETS_FOLDER = "review-sheets"


class Entry:
    """What a Review Sheet shows of one Problem: the index's view of it, plus its notes' details."""

    def __init__(self, notes):
        self.problem = to_problem(notes.rel, notes.fields, notes.attempts)
        self.key_takeaway = read_key_takeaway_line(notes.notes_file)
        # Oldest first by date; an Attempt with a malformed date sorts before every dated one.
        dated = [(a.fields.get("date", "") if is_date(a.fields.get("date", "")) else "", i) for i, a in enumerate(notes.attempts)]
        self.attempts = [notes.attempts[i].fields for _, i in sorted(dated)]
        self.redo = redo_reason(self.problem, self.attempts)


def redo_reason(problem, attempts):
    """Why to redo the Problem, or "" when there is no reason to."""
    if problem.need_review:
        return f"Need Review: {problem.reason}" if problem.reason else "Need Review"
    last_seen = None
    for attempt in attempts:
        if attempt.get("outcome") == "saw-solution":
            last_seen = attempt
        elif last_seen and attempt.get("mode") == "session" and attempt.get("outcome") == "solved-alone":
            last_seen = None
    if last_seen:
        return f"Saw the solution on {last_seen.get('date') or 'an undated Attempt'}, not solved alone since"
    return ""


def run(root, ids, tags, lists, title, output):
    if not (root / CONFIG_FILE).is_file():
        print(
            f"review-sheet: no {CONFIG_FILE} here, so this is not a Practice Workspace"
            " (create one with `practice-log init`)",
            file=sys.stderr,
        )
        return 1
    base = ""
    if output:
        label = output.as_posix()
        target, depth = sheet_path(root, output)
        if target is None:
            print(f"review-sheet: --output {label} is not a file inside the workspace's {SHEETS_FOLDER}/ folder", file=sys.stderr)
            return 1
        if target.exists():
            print(f"review-sheet: {label} already exists; choose another file name", file=sys.stderr)
            return 1
        base = "../" * depth

    notes = list(read_problems(root))
    errors = [n.error for n in notes if n.error]
    if errors:
        for error in errors:
            print(error, file=sys.stderr)
        print("review-sheet: nothing written; fix the notes (`practice-log validate` lists every error)", file=sys.stderr)
        return 1
    entries = [Entry(n) for n in notes]

    filters = Filters(ids, tags, lists)
    selected = [entry for entry in entries if filters.match(entry.problem)]
    for kind, value in filters.unmatched([entry.problem for entry in entries]):
        print(f"review-sheet: no Problem in the Practice Log has {kind} '{value}'", file=sys.stderr)

    sheet = render(title, filters, selected, base)
    redo = sum(1 for entry in selected if entry.redo)
    summary = f"{readme.plural(len(selected), 'Problem')}, {redo} to redo"
    if output:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(sheet, encoding="utf-8", newline="\n")
        print(f"review-sheet: wrote {label} ({summary})")
    else:
        sys.stdout.write(sheet)
    return 0


def sheet_path(root, output):
    """(resolved file, its depth below the workspace root) when `output` names a file inside the
    workspace's Review Sheet folder, else (None, 0). `output` is relative to the root."""
    sheets = (root / SHEETS_FOLDER).resolve()
    target = (root / output).resolve()
    try:
        inside = target.relative_to(sheets)
    except ValueError:  # outside the folder, or on another drive
        return None, 0
    if not inside.parts:
        return None, 0
    return target, len(inside.parts)


class Filters:
    """Problem IDs, tags and Problem List names; all of them match regardless of case."""

    def __init__(self, ids, tags, lists):
        self.ids = ids
        self.tags = tags
        self.lists = lists

    def match(self, problem):
        return all(not values or any(fold(value) in names for value in values) for values, names in self.kinds(problem))

    def unmatched(self, problems):
        """Each filter value that no Problem has, so the caller can fix a misspelt one."""
        for kind, index in (("id", 0), ("tag", 1), ("Problem List", 2)):
            for value in (self.ids, self.tags, self.lists)[index]:
                if not any(fold(value) in self.kinds(problem)[index][1] for problem in problems):
                    yield kind, value

    def kinds(self, problem):
        return [
            (self.ids, {fold(problem.id)}),
            (self.tags, {fold(tag) for tag in problem.tags}),
            (self.lists, {fold(name) for name in problem.lists}),
        ]

    def describe(self):
        parts = []
        for label, values in (("Problem IDs", self.ids), ("tags", self.tags), ("Problem Lists", self.lists)):
            if values:
                parts.append(f"{label} {', '.join(values)}")
        return "; ".join(parts) if parts else "none (every Problem)"


def fold(name):
    return name.casefold()


def render(title, filters, selected, base):
    selected = sorted(selected, key=lambda e: (e.problem.title.casefold(), e.problem.id, e.problem.folder))
    redo = [entry for entry in selected if entry.redo]
    refresh = [entry for entry in selected if not entry.redo]
    parts = [
        f"# {title}\n",
        f"{GENERATED}\n",
        f"Filters: {filters.describe()}.",
        f"{readme.plural(len(selected), 'Problem')}, {len(redo)} to redo.\n",
    ]
    if not selected:
        parts.append("No Problems in the Practice Log match.\n")
    if redo:
        parts.append("## Redo\n")
        parts += [entry_block(entry, base) for entry in redo]
    if refresh:
        parts.append("## Refresh\n")
        parts += [entry_block(entry, base) for entry in refresh]
    return "\n".join(parts)


def entry_block(entry, base):
    p = entry.problem
    details = [f"`{p.id}`"] + ([readme.difficulty(p)] if p.difficulty else [])
    lines = [f"### {readme.link(p, base)}\n", " · ".join(details) + "\n"]
    if entry.redo:
        lines.append(f"- **Redo:** {entry.redo}")
    lines.append(f"- **Key Takeaway:** {entry.key_takeaway or 'none recorded'}")
    if entry.attempts:
        approaches = [
            f"{a.get('approach') or '?'} ({a.get('date') or 'undated'}, {a.get('mode') or '?'}, {a.get('outcome') or '?'})"
            for a in entry.attempts
        ]
        lines.append(f"- **Approaches:** {'; '.join(approaches)}")
    else:
        lines.append("- **Approaches:** no Attempts yet")
    mistakes = [a for a in entry.attempts if a.get("mistakes") and a["mistakes"].strip().lower() != "none"]
    if mistakes:
        lines.append("- **Past mistakes:**")
        lines += [f"  - {a.get('date') or 'undated'}: {a['mistakes']}" for a in mistakes]
    else:
        lines.append("- **Past mistakes:** none recorded")
    tags = ", ".join(p.tags) or "none"
    lists = ", ".join(p.lists) or "none"
    lines.append(f"- **Tags:** {tags} · **Problem Lists:** {lists}")
    return "\n".join(lines) + "\n"
